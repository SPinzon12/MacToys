import CryptoKit
import Foundation

/// What the pasteboard offered at one `changeCount`, read once by the monitor.
/// Pure data so the capture rules are unit-testable without a real pasteboard.
struct PasteboardSnapshot {
    var types: [String]
    var text: String?
    var html: String?
    var fileURLs: [URL] = []
    var pngData: Data?
    var imageSize: CGSize?
    var sourceApp: String?
    var sourceBundleID: String?

    init(
        types: [String],
        text: String? = nil,
        html: String? = nil,
        fileURLs: [URL] = [],
        pngData: Data? = nil,
        imageSize: CGSize? = nil,
        sourceApp: String? = nil,
        sourceBundleID: String? = nil
    ) {
        self.types = types
        self.text = text
        self.html = html
        self.fileURLs = fileURLs
        self.pngData = pngData
        self.imageSize = imageSize
        self.sourceApp = sourceApp
        self.sourceBundleID = sourceBundleID
    }

    /// nspasteboard.org markers: password managers and clipboard tools tag
    /// secrets and throwaway writes so history apps leave them out.
    static let ignoredMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    var isIgnored: Bool { types.contains(where: Self.ignoredMarkers.contains) }
}

/// One clipboard history item. Images live as PNG files next to the index;
/// the entry only names its file.
struct ClipboardEntry: Codable, Identifiable, Equatable {
    enum Kind: String, Codable {
        case text
        case image
        case files
    }

    let id: UUID
    let kind: Kind
    var text: String?
    var html: String?
    var fileURLs: [URL]
    var imageFile: String?
    var imageSize: CGSize?
    /// SHA-256 of the content; identical copies share it and get promoted.
    let fingerprint: String
    var date: Date
    var sourceApp: String?
    var sourceBundleID: String?

    static func text(_ text: String, html: String?, date: Date, sourceApp: String?, sourceBundleID: String? = nil) -> ClipboardEntry {
        ClipboardEntry(
            id: UUID(), kind: .text, text: text, html: html, fileURLs: [],
            fingerprint: digest("t", Data(text.utf8)),
            date: date, sourceApp: sourceApp, sourceBundleID: sourceBundleID
        )
    }

    static func files(_ urls: [URL], date: Date, sourceApp: String?, sourceBundleID: String? = nil) -> ClipboardEntry {
        ClipboardEntry(
            id: UUID(), kind: .files, fileURLs: urls,
            fingerprint: digest("f", Data(urls.map(\.path).joined(separator: "\n").utf8)),
            date: date, sourceApp: sourceApp, sourceBundleID: sourceBundleID
        )
    }

    static func image(pngData: Data, size: CGSize?, date: Date, sourceApp: String?, sourceBundleID: String? = nil) -> ClipboardEntry {
        let id = UUID()
        return ClipboardEntry(
            id: id, kind: .image, fileURLs: [],
            imageFile: "\(id.uuidString).png", imageSize: size,
            fingerprint: digest("i", pngData),
            date: date, sourceApp: sourceApp, sourceBundleID: sourceBundleID
        )
    }

    /// Capture rules: marked secrets and empty content are skipped; files win
    /// over text (Finder also puts names on the pasteboard), and text wins over
    /// an image (spreadsheets and editors attach a rendered picture of the text).
    static func capture(_ snapshot: PasteboardSnapshot, date: Date) -> ClipboardEntry? {
        guard !snapshot.isIgnored else { return nil }
        let app = snapshot.sourceApp
        let bundle = snapshot.sourceBundleID
        if !snapshot.fileURLs.isEmpty {
            return .files(snapshot.fileURLs, date: date, sourceApp: app, sourceBundleID: bundle)
        }
        if let text = snapshot.text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text, html: snapshot.html, date: date, sourceApp: app, sourceBundleID: bundle)
        }
        if let png = snapshot.pngData, !png.isEmpty {
            return .image(pngData: png, size: snapshot.imageSize, date: date, sourceApp: app, sourceBundleID: bundle)
        }
        return nil
    }

    /// Everything the search field matches against.
    var searchableText: String {
        var parts: [String] = []
        switch kind {
        case .text: parts.append(text ?? "")
        case .files: parts.append(contentsOf: fileURLs.map(\.lastPathComponent))
        case .image: parts.append("image")
        }
        if let sourceApp { parts.append(sourceApp) }
        return parts.joined(separator: " ")
    }

    private static func digest(_ prefix: String, _ data: Data) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(prefix.utf8))
        hasher.update(data: data)
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}
