import Foundation
import Testing
@testable import MacPowerToys

/// Clipboard history: capture rules, dedupe/cap ordering, search, persistence.
struct ClipboardHistoryTests {
    private let t0 = Date(timeIntervalSince1970: 1_800_000_000)

    private func text(_ value: String, at offset: TimeInterval = 0) -> ClipboardEntry {
        ClipboardEntry.text(value, html: nil, date: t0.addingTimeInterval(offset), sourceApp: nil)
    }

    // MARK: - Capture

    @Test func concealedTransientAndAutoGeneratedPasteboardsAreIgnored() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            let snapshot = PasteboardSnapshot(types: ["public.utf8-plain-text", marker], text: "hunter2")
            #expect(ClipboardEntry.capture(snapshot, date: t0) == nil, "\(marker) must not be recorded")
        }
    }

    @Test func emptyOrWhitespaceTextIsIgnored() {
        #expect(ClipboardEntry.capture(PasteboardSnapshot(types: [], text: ""), date: t0) == nil)
        #expect(ClipboardEntry.capture(PasteboardSnapshot(types: [], text: " \n\t"), date: t0) == nil)
        #expect(ClipboardEntry.capture(PasteboardSnapshot(types: []), date: t0) == nil)
    }

    @Test func captureKeepsTextHTMLAndSourceApp() throws {
        let snapshot = PasteboardSnapshot(types: [], text: "hello", html: "<b>hello</b>", sourceApp: "Safari")
        let entry = try #require(ClipboardEntry.capture(snapshot, date: t0))
        #expect(entry.kind == .text)
        #expect(entry.text == "hello")
        #expect(entry.html == "<b>hello</b>")
        #expect(entry.sourceApp == "Safari")
        #expect(entry.date == t0)
    }

    @Test func capturePrefersFilesThenTextThenImage() throws {
        let file = URL(fileURLWithPath: "/tmp/report.pdf")
        let png = Data([0x89, 0x50, 0x4E, 0x47])
        let all = PasteboardSnapshot(types: [], text: "report.pdf", fileURLs: [file], pngData: png, imageSize: CGSize(width: 2, height: 2))
        #expect(try #require(ClipboardEntry.capture(all, date: t0)).kind == .files)

        let textAndImage = PasteboardSnapshot(types: [], text: "cell", pngData: png, imageSize: CGSize(width: 2, height: 2))
        #expect(try #require(ClipboardEntry.capture(textAndImage, date: t0)).kind == .text)

        let imageOnly = PasteboardSnapshot(types: [], pngData: png, imageSize: CGSize(width: 2, height: 2))
        let image = try #require(ClipboardEntry.capture(imageOnly, date: t0))
        #expect(image.kind == .image)
        #expect(image.imageFile == "\(image.id.uuidString).png")
    }

    // MARK: - Ordering

    @Test func recordPutsNewestFirst() {
        var history = ClipboardHistory()
        history.record(text("a"))
        history.record(text("b", at: 1))
        #expect(history.entries.map(\.text) == ["b", "a"])
    }

    @Test func identicalContentIsPromotedNotDuplicated() {
        var history = ClipboardHistory()
        let first = text("a")
        history.record(first)
        history.record(text("b", at: 1))
        let outcome = history.record(text("a", at: 2))

        #expect(outcome.inserted == false)
        #expect(history.entries.map(\.text) == ["a", "b"])
        #expect(history.entries[0].id == first.id) // keeps identity (and image file)
        #expect(history.entries[0].date == t0.addingTimeInterval(2))
    }

    @Test func capEvictsOldestAndReportsThem() {
        var history = ClipboardHistory(limit: 2)
        history.record(text("a"))
        history.record(text("b", at: 1))
        let outcome = history.record(text("c", at: 2))

        #expect(outcome.inserted)
        #expect(outcome.evicted.map(\.text) == ["a"])
        #expect(history.entries.map(\.text) == ["c", "b"])
    }

    @Test func promoteMovesEntryToTop() {
        var history = ClipboardHistory()
        let a = text("a")
        history.record(a)
        history.record(text("b", at: 1))
        history.promote(a.id, date: t0.addingTimeInterval(5))
        #expect(history.entries.map(\.text) == ["a", "b"])
        #expect(history.entries[0].date == t0.addingTimeInterval(5))
    }

    @Test func removeAllEmptiesAndReturnsEverything() {
        var history = ClipboardHistory()
        history.record(text("a"))
        history.record(text("b", at: 1))
        #expect(history.removeAll().count == 2)
        #expect(history.entries.isEmpty)
    }

    // MARK: - Search

    @Test func filterMatchesEveryTokenIgnoringCaseAndDiacritics() {
        var history = ClipboardHistory()
        history.record(text("Café con leche"))
        history.record(text("cafe americano", at: 1))
        history.record(text("té verde", at: 2))

        #expect(history.filtered("").count == 3)
        #expect(history.filtered("  ").count == 3)
        #expect(history.filtered("CAFE").map(\.text) == ["cafe americano", "Café con leche"])
        #expect(history.filtered("cafe leche").map(\.text) == ["Café con leche"])
        #expect(history.filtered("matcha").isEmpty)
    }

    @Test func filterSearchesFileNamesAndSourceApp() {
        var history = ClipboardHistory()
        history.record(.files([URL(fileURLWithPath: "/tmp/Invoice-2026.pdf")], date: t0, sourceApp: "Finder"))
        history.record(.text("note", html: nil, date: t0.addingTimeInterval(1), sourceApp: "Notes"))

        #expect(history.filtered("invoice").count == 1)
        #expect(history.filtered("finder").count == 1)
        #expect(history.filtered("notes").map(\.text) == ["note"])
    }

    // MARK: - Sections

    @Test func sectionsGroupByDay() {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "UTC")!
        let now = t0
        #expect(ClipboardHistory.section(for: now.addingTimeInterval(-60), now: now, calendar: calendar) == .today)
        #expect(ClipboardHistory.section(for: now.addingTimeInterval(-86_400), now: now, calendar: calendar) == .yesterday)
        #expect(ClipboardHistory.section(for: now.addingTimeInterval(-86_400 * 3), now: now, calendar: calendar) == .earlier)
    }

    // MARK: - Persistence

    @Test func storeRoundTripsHistoryWithOwnerOnlyPermissions() throws {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("mpt-history-\(UUID().uuidString)", isDirectory: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let store = ClipboardHistoryStore(directory: dir)

        var history = ClipboardHistory(limit: 50)
        history.record(text("persisted"))
        try store.save(history)

        let loaded = store.load()
        #expect(loaded.limit == 50)
        #expect(loaded.entries.map(\.text) == ["persisted"])
        #expect(loaded.entries[0].id == history.entries[0].id)

        let attributes = try FileManager.default.attributesOfItem(atPath: store.indexURL.path)
        #expect((attributes[.posixPermissions] as? NSNumber)?.intValue == 0o600)
    }

    @Test func storeWritesAndDeletesImageFiles() throws {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("mpt-history-\(UUID().uuidString)", isDirectory: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let store = ClipboardHistoryStore(directory: dir)
        let png = Data([1, 2, 3])
        let entry = try #require(ClipboardEntry.capture(
            PasteboardSnapshot(types: [], pngData: png, imageSize: CGSize(width: 1, height: 1)),
            date: t0
        ))

        try store.writeImage(png, for: entry)
        #expect(store.imageData(for: entry) == png)
        store.deleteImages(of: [entry])
        #expect(store.imageData(for: entry) == nil)
    }

    @Test func missingOrCorruptIndexLoadsEmpty() throws {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("mpt-history-\(UUID().uuidString)", isDirectory: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let store = ClipboardHistoryStore(directory: dir)
        #expect(store.load().entries.isEmpty)

        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try Data("not json".utf8).write(to: store.indexURL)
        #expect(store.load().entries.isEmpty)
    }
}
